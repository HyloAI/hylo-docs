"""Pages generated at build time from the code repositories checked out next to this one (the development workspace,
harness/dev/bootstrap.sh): the harness reference docs, the CLI reference, the plugin catalogue, the example index,
the format schemas and the API reference of every package. Run by mkdocs-gen-files; a repository that is not checked out gives a page that says so.
"""

from __future__ import annotations

import json
import posixpath
import re
import subprocess
import sys
from pathlib import Path

import mkdocs_gen_files

DOCS_REPO = Path(__file__).resolve().parents[1]
WORKSPACE = DOCS_REPO.parent
HARNESS = WORKSPACE / "harness"
GENERATED = "<!-- generated by mkdocs/gen_pages.py at build time; edit the source, not this page -->\n\n"


def write(path: str, text: str, source: Path | None = None) -> None:
    with mkdocs_gen_files.open(path, "w") as f:
        f.write(GENERATED + text)
    if source is not None:
        mkdocs_gen_files.set_edit_path(path, str(source))


def missing(repo: str) -> str:
    return (f"!!! warning \"Not built\"\n    This page is generated from hylo-{repo}, which is not checked out next to "
            f"this repository. Build the docs from the development workspace (see Getting started > Installation).\n")


# ---------------------------------------------------------------- harness reference docs
def harness_docs() -> None:
    src = HARNESS / "docs"
    for f in sorted(src.rglob("*.md")) if src.is_dir() else []:
        rel = f.relative_to(src).as_posix()
        text = f.read_text()
        note = f"!!! note \"Source\"\n    Maintained in hylo-harness: `docs/{rel}`.\n\n"
        title, _, body = text.partition("\n")
        write(f"harness/{rel}", f"{title}\n\n{note}{body}", f)
    if not src.is_dir():
        for name in ("extending", "plugin-system", "experiment-schema", "execution-lifecycle", "dependency-graph"):
            write(f"harness/{name}.md", f"# {name}\n\n{missing('harness')}")


# ---------------------------------------------------------------- CLI reference
def _help(*args: str) -> str:
    out = subprocess.run([sys.executable, "-m", "hylo.core.cli", *args, "--help"], capture_output=True,
                         text=True, timeout=120, cwd=WORKSPACE)
    return (out.stdout or out.stderr).strip()


def cli_reference() -> None:
    try:
        top = _help()
    except (OSError, subprocess.SubprocessError):
        write("cli/index.md", "# CLI Reference\n\n" + missing("harness"))
        return
    commands = re.findall(r"^  ([a-z][a-z-]*)\s{2,}(.+)$", top, re.M)
    lines = ["# CLI Reference", "",
             "`hylo` is one command whose subcommands come from the installed Hylo packages (the "
             "`hylo.commands` entry-point group): what is listed here depends on which repositories are "
             "installed. Choose a command family for its generated `--help` and subcommands.", "",
             "| Command | What it does |", "|---|---|"]
    lines += [f"| [`hylo {c}`](commands/{c}.md) | {d} |" for c, d in commands]
    for c, description in commands:
        text = _help(c)
        detail = [f"# hylo {c}", "", description, "", "[All commands](../index.md)",
                  "", "```text", text, "```"]
        # Keep existing command anchors useful without repeating the full help on the index.
        lines += ["", f"## hylo {c}", "", f"[{description}](commands/{c}.md)"]
        usage = text.split("\n\n")[0]
        subs = re.search(r"\{([a-z,_-]+)\}", usage)
        for sub in (subs.group(1).split(",") if subs else []):
            detail += ["", f"## hylo {c} {sub}", "", "```text", _help(c, sub), "```"]
            lines += ["", f"### hylo {c} {sub}", "",
                      f"[Arguments and defaults](commands/{c}.md#hylo-{c}-{sub})."]
        write(f"cli/commands/{c}.md", "\n".join(detail) + "\n")
    write("cli/index.md", "\n".join(lines) + "\n")


# ---------------------------------------------------------------- plugin catalogue
def plugin_catalogue() -> None:
    try:
        from hylo.core.plugins import CONTRACTS, catalogue
    except ImportError:
        write("developer-guide/plugin-catalogue.md", "# Plugin catalogue\n\n" + missing("harness"))
        return
    metas = [m for m in catalogue() if m.maturity != "test-double"]
    counts: dict[str, int] = {}
    for m in metas:
        counts[m.maturity] = counts.get(m.maturity, 0) + 1
    badge = {"implemented": '<span class="hylo-badge hylo-ok">implemented</span>',
             "unverified": '<span class="hylo-badge hylo-warn">unverified</span>',
             "needs-hardware": '<span class="hylo-badge hylo-hw">needs hardware</span>'}
    lines = ["# Plugin catalogue", "",
             "Every plugin installed in the development workspace, with the contract version it implements, how far it "
             "has been verified and its licences (`hylo plugins`). Maturity is declared by each "
             "package and was set from recorded runs:", "",
             "- **implemented**: run end to end on its target (a real simulator or robot), with recorded runs;",
             "- **unverified**: tests pass, but not yet run end to end on its intended target;",
             "- **needs hardware**: needs hardware that is not connected yet.", "",
             " · ".join(f"**{n}** {k}" for k, n in sorted(counts.items(), key=lambda kv: -kv[1])), ""]
    for group, contract in CONTRACTS.items():
        rows = [m for m in metas if m.group == group]
        if not rows:
            continue
        lines += [f"## {group}", "", f"Contract `{contract}`.", "",
                  "| Plugin | Package | Maturity | Licence | Weights / notes |", "|---|---|---|---|---|"]
        for m in rows:
            extra = "; ".join(x for x in (m.weights and f"weights: {m.weights}", m.notes) if x)
            lines.append(f"| `{m.name}` | {m.distribution} | {badge.get(m.maturity, m.maturity)} | {m.licence or '-'} "
                         f"| {extra or ''} |")
        lines.append("")
    write("developer-guide/plugin-catalogue.md", "\n".join(lines))


# ---------------------------------------------------------------- examples
def _header(path: Path) -> str:
    out = []
    for line in path.read_text().splitlines():
        if not line.startswith("#"):
            break
        out.append(line[1:].strip())
    return " ".join(out)


def examples() -> None:
    groups = [("bench", "examples/configs", "Experiments", "hylo run {path}"),
              ("bench", "examples/evolve", "Improvement campaigns", "hylo evolve run {path}"),
              ("plugins", "examples/configs", "Plugin examples: experiments", "hylo run {path}"),
              ("plugins", "examples/evolve", "Plugin examples: campaigns", "hylo evolve run {path}")]
    lines = ["# Example catalogue", "",
             "Every example config in hylo-bench and hylo-plugins, with the comment at its top. "
             "Run these commands from the **workspace root**, where `bench/` and `plugins/` are siblings. "
             "Config paths are relative to the working directory; runtimes and artifact ids resolve through the "
             "machine profile and store.", "",
             "For a guided first run, use the [quickstart](quickstart.md). "
             "[Next steps](next-steps.md) matches tasks to guides and prerequisites.", ""]
    for repo, sub, title, cmd in groups:
        d = WORKSPACE / repo / sub
        if not d.is_dir():
            lines += [f"## {title}", "", missing(repo)]
            continue
        lines += [f"## {title}", "", "| Example | What it shows |", "|---|---|"]
        for f in sorted(d.glob("*.yaml")):
            lines.append(f"| [`{f.stem}`](#{repo}-{f.stem.replace('_', '-')}) | {_header(f) or '-'} |")
        lines.append("")
        for f in sorted(d.glob("*.yaml")):
            path = f"{repo}/{sub}/{f.name}"
            lines += [f"### {f.stem} {{ #{repo}-{f.stem.replace('_', '-')} }}", "",
                      f"```bash\nuv run {cmd.format(path=path)}\n```", "",
                      f'??? example "{path}"', "", "    ```yaml",
                      *[f"    {l}" for l in f.read_text().rstrip().splitlines()], "    ```", ""]
    scripts = [WORKSPACE / "bench/examples/policies/compare.py", WORKSPACE / "bench/examples/rsi_demo.py"]
    lines += ["## Scripts", "", "| Script | What it does |", "|---|---|"]
    for s in scripts:
        if s.exists():
            doc = re.search(r'^"""(.+?)$', s.read_text(), re.M)
            lines.append(f"| `{s.relative_to(WORKSPACE)}` | {doc.group(1) if doc else '-'} |")
    write("getting-started/examples.md", "\n".join(lines) + "\n")


