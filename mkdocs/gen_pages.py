SKIP_MODULE = re.compile(r"(^|\.)(_[^.]+|tests?|static|workers|__main__)(\.|$)")


def _modules(src: Path) -> list[str]:
    out = []
    for f in sorted(src.rglob("*.py")):
        # Workers execute as scripts in their own environment (or Blender), not importable package APIs.
        header = f.read_text()[:512]
        if "# /// script" in header or "# hylo: worker-side" in header:
            continue
        rel = f.relative_to(src).with_suffix("")
        parts = list(rel.parts[:-1]) if rel.name == "__init__" else list(rel.parts)
        name = ".".join(parts)
        if name and not SKIP_MODULE.search(name):
            out.append(name)
    return sorted(set(out))


def _first_line(src: Path, module: str) -> str:
    f = src.joinpath(*module.split("."))
    # Asset directories can share a module's stem (for example motion_characters/ and motion_characters.py).
    package_init = f / "__init__.py"
    f = package_init if package_init.is_file() else f.with_suffix(".py")
    m = re.match(r'\s*(?:#.*\n\s*)*(?:from __future__.*\n\s*)?[rRbB]?("""|\'\'\')(.*?)(\n|\1)', f.read_text())
    return m.group(2).strip().rstrip(".") if m else ""


def _curated() -> dict[str, str]:
    """Modules the hand-written core pages already render: {module: page}, so they are rendered once."""
    out = {}
    for page in sorted((DOCS_REPO / "docs" / "api").glob("*.md")):
        for m in re.findall(r"^::: ([\w.]+)", page.read_text(), re.M):
            out[m] = page.name
    return out


def package_api() -> None:
    import tomllib

    curated = _curated()

    index = ["# Packages", "",
             "The API of every Hylo package, generated from its docstrings and type annotations (mkdocstrings). "
             "Plugins and leaf repositories should depend on the [core contracts](../index.md) only; the rest is "
             "documented by module so that it can be read, extended and debugged. Members whose names start with an underscore "
             "are left out.", ""]
    for repo, dirs in PACKAGES.items():
        index += [f"## hylo-{repo}", "", "| Package | What it is | Modules |", "|---|---|---|"]
        for d in dirs:
            root = WORKSPACE / repo / d
            dist = Path(d).name
            if not (root / "pyproject.toml").exists():
                write(f"api/packages/{dist}.md", f"# {dist}\n\n{missing(repo)}")
                index.append(f"| [{dist}]({dist}.md) | not checked out | - |")
                continue
            proj = tomllib.loads((root / "pyproject.toml").read_text())["project"]
            src = root / "src"
            mods = _modules(src)
            lines = [f"# {dist}", "", proj.get("description", ""), "",
                     f"Repository hylo-{repo}, `{d}`. Licence: {proj.get('license', '-')}. "
                     f"Depends on: {', '.join(f'`{x}`' for x in proj.get('dependencies', [])) or 'nothing'}.", ""]
            eps = proj.get("entry-points", {})
            plug = [(g.removeprefix("hylo."), n, v) for g, items in eps.items()
                    if g.startswith("hylo.") and g not in ("hylo.meta",) for n, v in items.items()]
            if plug:
                lines += ["??? info \"Registered entry points\"", "", "    | Group | Name | Object |", "    |---|---|---|",
                          *[f"    | {g} | `{n}` | `{v}` |" for g, n, v in sorted(plug)], ""]
            def module_target(module: str) -> str:
                if module in curated:
                    return f"../{curated[module]}#{module}"
                return f"../modules/{dist}/{module}.md"

            lines += ["| Module | Summary |", "|---|---|",
                      *[f"| [`{m}`]({module_target(m)}) | {_first_line(src, m)} |" for m in mods], ""]
            for m in mods:
                if m in curated:
                    lines += [f"## `{m}` {{ #{m.replace('.', '')} }}", "",
                              f"A core contract: documented in [{curated[m][:-3].replace('-', ' ')}](../{curated[m]}#{m}).", ""]
                    continue
                lines += [f"## `{m}` {{ #{m.replace('.', '')} }}", "",
                          f'[Module API]({module_target(m)}){{ data-api-module="{m}" }}. '
                          f"{_first_line(src, m)}", ""]
                detail = [f"# {m}", "", f"[Package: {dist}](../../packages/{dist}.md) · "
                          "[Core contracts](../../index.md)", "", f"::: {m}", "    options:",
                          "      show_root_heading: true", "      heading_level: 2", "      show_submodules: false",
                          "      members_order: source", "      show_if_no_docstring: true", ""]
                write(f"api/modules/{dist}/{m}.md", "\n".join(detail))
            write(f"api/packages/{dist}.md", "\n".join(lines))
            summary = proj.get("description", "").split(":")[-1].strip()
            index.append(f"| [{dist}]({dist}.md) | {summary} | {len(mods)} |")
        index.append("")
    write("api/packages/index.md", "\n".join(index))


